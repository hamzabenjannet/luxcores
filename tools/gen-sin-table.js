// Generates src/sim/sin-table.js: 4096 integer sine values scaled by 65536.
//
// This is the only place Math.sin is allowed. It runs once on a dev machine
// and the output is committed, so every runtime (browsers, Node, the future
// Rust core) reads identical integers.
//
// Usage: node tools/gen-sin-table.js

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const N = 4096;
const SCALE = 65536;
const values = [];
for (let i = 0; i < N; i++) {
  values.push(Math.round(Math.sin((2 * Math.PI * i) / N) * SCALE));
}

// Force exact values at the quarter turns.
values[0] = 0;
values[N / 4] = SCALE;
values[N / 2] = 0;
values[(3 * N) / 4] = -SCALE;

const lines = [];
for (let i = 0; i < N; i += 16) lines.push('  ' + values.slice(i, i + 16).join(', ') + ',');

const out = `// GENERATED by tools/gen-sin-table.js. Do not edit by hand.
// sin(2*PI*i/${N}) * ${SCALE}, rounded to the nearest integer.

export const SIN_SCALE = ${SCALE};

/** @type {readonly number[]} */
export const SIN_TABLE = Object.freeze([
${lines.join('\n')}
]);
`;

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, '..', 'src', 'sim', 'sin-table.js'), out);
console.log(`wrote ${N} entries`);
